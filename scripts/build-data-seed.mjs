import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const outputRoot = resolve(process.argv[2] ?? '.data-seed')
const templateIds = ['common', 'python-ai', 'java-web', 'data-analytics', 'generative-ai']

const readJson = async (path) => JSON.parse(await readFile(resolve(path), 'utf8'))
const writeJson = async (path, value) => {
  const target = resolve(outputRoot, path)
  await mkdir(dirname(target), { recursive: true })
  await writeFile(target, `${JSON.stringify(value, null, 2)}\n`, 'utf8')
}

const templates = await Promise.all(templateIds.map((id) => readJson(`src/data/templates/${id}.json`)))
const stackCatalog = await readJson('src/data/stack-catalog.json')
const common = templates.find((template) => template.templateId === 'common')
const pythonAi = templates.find((template) => template.templateId === 'python-ai')
const selectedStacks = ['python', 'pandas', 'tensorflow']
const questions = [...common.questions, ...pythonAi.questions]
const questionIds = new Set(questions.map((question) => question.id))

for (const stack of stackCatalog.stacks.filter((candidate) => selectedStacks.includes(candidate.id))) {
  for (const question of stack.questions) {
    if (!questionIds.has(question.id)) {
      questions.push({ ...question, sourceStack: stack.id, autoGenerated: true })
      questionIds.add(question.id)
    }
  }
}

const demoSurvey = {
  schemaVersion: 1,
  surveyId: 'demo-python-ai-2026',
  revision: 1,
  title: 'Python·AI 과정 사전 이해도 조사',
  description: '수업 난이도와 실습 속도를 조정하기 위한 데모 설문입니다. 개인정보를 적지 마세요.',
  course: { id: 'python-ai', name: 'Python·AI', cohort: '데모 1기' },
  status: 'published',
  createdAt: '2026-10-23T08:00:00.000Z',
  selectedStacks,
  questions,
}

await Promise.all(templates.map((template) => writeJson(`templates/${template.templateId}.json`, template)))
await writeJson('templates/stack-catalog.json', stackCatalog)
await writeJson('templates/index.json', {
  schemaVersion: 1,
  templates: templates.map((template) => ({ templateId: template.templateId, path: `templates/${template.templateId}.json`, name: template.name })),
})
await writeJson('surveys/index.json', {
  schemaVersion: 1,
  surveys: [{ surveyId: demoSurvey.surveyId, title: demoSurvey.title, courseName: demoSurvey.course.name, cohort: demoSurvey.course.cohort, revision: demoSurvey.revision, status: demoSurvey.status }],
})
await writeJson(`surveys/${demoSurvey.surveyId}/survey.json`, demoSurvey)
await writeJson(`surveys/${demoSurvey.surveyId}/revisions/1.json`, demoSurvey)

console.log(`Data branch seed created at ${outputRoot}`)
