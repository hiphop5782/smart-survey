import { z } from 'zod'
import { QUESTION_TYPES, type EncryptedSurveyResponse, type Survey, type SurveyResponse } from './types'

const optionSchema = z.object({
  value: z.string().min(1),
  label: z.string().min(1),
})

const showIfSchema = z.object({
  questionId: z.string().min(1),
  equals: z.union([z.string(), z.number(), z.boolean()]).optional(),
  notEquals: z.union([z.string(), z.number(), z.boolean()]).optional(),
  includes: z.string().optional(),
})

const questionSchema = z
  .object({
    id: z.string().regex(/^[a-zA-Z][a-zA-Z0-9_-]*$/, '문항 ID 형식이 올바르지 않습니다.'),
    type: z.enum(QUESTION_TYPES),
    title: z.string().min(1),
    description: z.string().optional(),
    required: z.boolean().optional(),
    options: z.array(optionSchema).optional(),
    validation: z
      .object({
        minLength: z.number().int().nonnegative().optional(),
        maxLength: z.number().int().positive().optional(),
        minSelections: z.number().int().nonnegative().optional(),
        maxSelections: z.number().int().positive().optional(),
      })
      .optional(),
    showIf: showIfSchema.optional(),
    category: z.string().optional(),
    sourceStack: z.string().optional(),
    autoGenerated: z.boolean().optional(),
    language: z.string().optional(),
    code: z.string().optional(),
    min: z.number().optional(),
    max: z.number().optional(),
    minLabel: z.string().optional(),
    maxLabel: z.string().optional(),
    terms: z.array(optionSchema).optional(),
    levels: z.array(optionSchema).optional(),
  })
  .superRefine((question, context) => {
    if (['single', 'multiple', 'codeFamiliarity', 'codeQuiz'].includes(question.type) && (!question.options || question.options.length < 2)) {
      context.addIssue({ code: 'custom', message: '선택형 문항에는 선택지가 2개 이상 필요합니다.' })
    }
    if (['codeFamiliarity', 'codeQuiz'].includes(question.type) && (!question.language || !question.code)) {
      context.addIssue({ code: 'custom', message: '코드 문항에는 언어와 코드가 필요합니다.' })
    }
    if (question.type === 'scale' && (question.min === undefined || question.max === undefined || question.min >= question.max)) {
      context.addIssue({ code: 'custom', message: '척도 문항의 최솟값과 최댓값을 확인하세요.' })
    }
    if (question.type === 'termMatrix' && (!question.terms?.length || !question.levels?.length)) {
      context.addIssue({ code: 'custom', message: '용어 매트릭스에는 용어와 인지도 단계가 필요합니다.' })
    }
  })

export const surveySchema = z
  .object({
    schemaVersion: z.literal(1),
    surveyId: z.string().regex(/^[a-z0-9][a-z0-9-]{2,63}$/, '설문 ID는 영문 소문자, 숫자, 하이픈만 사용할 수 있습니다.'),
    revision: z.number().int().positive(),
    title: z.string().min(1),
    description: z.string().optional(),
    course: z.object({
      id: z.string().min(1),
      name: z.string().min(1),
      cohort: z.string().min(1),
    }),
    status: z.enum(['draft', 'published', 'closed']),
    createdAt: z.string().datetime(),
    updatedAt: z.string().datetime().optional(),
    selectedStacks: z.array(z.string()).optional(),
    questions: z.array(questionSchema).min(1),
  })
  .superRefine((survey, context) => {
    const seen = new Set<string>()
    survey.questions.forEach((question, index) => {
      if (seen.has(question.id)) {
        context.addIssue({ code: 'custom', path: ['questions', index, 'id'], message: `중복 문항 ID: ${question.id}` })
      }
      seen.add(question.id)
      if (question.showIf && !survey.questions.some((candidate) => candidate.id === question.showIf?.questionId)) {
        context.addIssue({ code: 'custom', path: ['questions', index, 'showIf'], message: '조건이 참조하는 문항을 찾을 수 없습니다.' })
      }
    })
  })

const answerValueSchema = z.union([
  z.string(),
  z.number(),
  z.array(z.string()),
  z.record(z.string(), z.string()),
  z.null(),
])

export const responseSchema = z.object({
  schemaVersion: z.literal(1),
  surveyId: z.string().min(1),
  revision: z.number().int().positive(),
  responseId: z.string().uuid(),
  submittedAt: z.string().datetime(),
  answers: z.record(z.string(), answerValueSchema),
})

export const encryptedResponseSchema = z.object({
  schemaVersion: z.literal(1),
  surveyId: z.string().regex(/^[a-z0-9][a-z0-9-]{2,63}$/),
  revision: z.number().int().positive(),
  responseId: z.string().uuid(),
  submittedAt: z.string().datetime(),
  encrypted: z.literal(true),
  encryption: z.object({
    algorithm: z.literal('RSA-OAEP-256+A256GCM'),
    encryptedKey: z.string().min(1),
    iv: z.string().min(1),
    ciphertext: z.string().min(1),
  }),
})

export function parseSurvey(value: unknown): Survey {
  return surveySchema.parse(value) as Survey
}

export function parseSurveyResponse(value: unknown): SurveyResponse {
  return responseSchema.parse(value) as SurveyResponse
}

export function parseEncryptedSurveyResponse(value: unknown): EncryptedSurveyResponse {
  return encryptedResponseSchema.parse(value) as EncryptedSurveyResponse
}

export function formatSchemaError(error: unknown): string {
  if (!(error instanceof z.ZodError)) return error instanceof Error ? error.message : '알 수 없는 검증 오류가 발생했습니다.'
  return error.issues.map((issue) => `${issue.path.join('.') || 'root'}: ${issue.message}`).join('\n')
}
