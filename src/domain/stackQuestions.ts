import type { Question, StackDefinition } from './types'

export function syncStackQuestions(
  questions: Question[],
  selectedStackIds: string[],
  definitions: StackDefinition[],
): Question[] {
  const selected = new Set(selectedStackIds)
  const manualAndSelected = questions.filter((question) => !question.autoGenerated || (question.sourceStack && selected.has(question.sourceStack)))
  const existingIds = new Set(manualAndSelected.map((question) => question.id))
  const additions: Question[] = []

  definitions
    .filter((definition) => selected.has(definition.id))
    .forEach((definition) => {
      definition.questions.forEach((question) => {
        if (!existingIds.has(question.id)) {
          additions.push({ ...question, sourceStack: definition.id, autoGenerated: true })
          existingIds.add(question.id)
        }
      })
    })

  return [...manualAndSelected, ...additions]
}

export function createQuestionId(prefix: string, existingQuestions: Question[]): string {
  const safePrefix = prefix.replace(/[^a-zA-Z0-9_-]/g, '') || 'question'
  let index = 1
  let candidate = `${safePrefix}${index}`
  const ids = new Set(existingQuestions.map((question) => question.id))
  while (ids.has(candidate)) {
    index += 1
    candidate = `${safePrefix}${index}`
  }
  return candidate
}
