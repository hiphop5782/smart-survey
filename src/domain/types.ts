export const QUESTION_TYPES = [
  'single',
  'multiple',
  'shortText',
  'longText',
  'scale',
  'codeFamiliarity',
  'termMatrix',
  'codeQuiz',
] as const

export type QuestionType = (typeof QUESTION_TYPES)[number]

export interface Option {
  value: string
  label: string
}

export interface QuestionValidation {
  minLength?: number
  maxLength?: number
  minSelections?: number
  maxSelections?: number
}

export interface ShowIf {
  questionId: string
  equals?: string | number | boolean
  notEquals?: string | number | boolean
  includes?: string
}

export interface BaseQuestion {
  id: string
  type: QuestionType
  title: string
  description?: string
  required?: boolean
  options?: Option[]
  validation?: QuestionValidation
  showIf?: ShowIf
  category?: string
  sourceStack?: string
  autoGenerated?: boolean
}

export interface CodeQuestion extends BaseQuestion {
  type: 'codeFamiliarity' | 'codeQuiz'
  language: string
  code: string
}

export interface ScaleQuestion extends BaseQuestion {
  type: 'scale'
  min: number
  max: number
  minLabel?: string
  maxLabel?: string
}

export interface TermMatrixQuestion extends BaseQuestion {
  type: 'termMatrix'
  terms: Option[]
  levels: Option[]
}

export type Question = BaseQuestion | CodeQuestion | ScaleQuestion | TermMatrixQuestion

export interface Survey {
  schemaVersion: 1
  surveyId: string
  revision: number
  title: string
  description?: string
  course: {
    id: string
    name: string
    cohort: string
  }
  status: 'draft' | 'published' | 'closed'
  createdAt: string
  updatedAt?: string
  selectedStacks?: string[]
  questions: Question[]
}

export type AnswerValue = string | number | string[] | Record<string, string> | null

export interface SurveyResponse {
  schemaVersion: 1
  surveyId: string
  revision: number
  responseId: string
  submittedAt: string
  answers: Record<string, AnswerValue>
}

export interface EncryptedSurveyResponse {
  schemaVersion: 1
  surveyId: string
  revision: number
  responseId: string
  submittedAt: string
  encrypted: true
  encryption: {
    algorithm: 'RSA-OAEP-256+A256GCM'
    encryptedKey: string
    iv: string
    ciphertext: string
  }
}

export interface StackDefinition {
  id: string
  label: string
  group: string
  description: string
  questions: Question[]
}

export interface TemplateDefinition {
  schemaVersion: 1
  templateId: string
  name: string
  description: string
  recommendedStacks: string[]
  questions: Question[]
}

export interface SurveyIndexItem {
  surveyId: string
  title: string
  courseName: string
  cohort: string
  revision: number
  status: Survey['status']
}

export interface DistributionItem {
  value: string
  label: string
  count: number
  percentage: number
}

export interface QuestionSummary {
  questionId: string
  title: string
  type: QuestionType
  answered: number
  missing: number
  distribution?: DistributionItem[]
  textValues?: string[]
  matrix?: Record<string, DistributionItem[]>
  correctCount?: number
  correctRate?: number
}

export interface AnalyticsSummary {
  totalResponses: number
  totalMissingAnswers: number
  questions: QuestionSummary[]
}
