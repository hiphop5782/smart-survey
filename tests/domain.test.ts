import { describe, expect, it } from 'vitest'
import { calculateAnalytics, responsesToCsv } from '../src/domain/analytics'
import { parseSurvey, parseSurveyResponse } from '../src/domain/schema'
import { syncStackQuestions } from '../src/domain/stackQuestions'
import { isQuestionVisible, validateQuestionAnswer } from '../src/domain/visibility'
import type { Question, StackDefinition, Survey, SurveyResponse } from '../src/domain/types'

const baseSurvey: Survey = {
  schemaVersion: 1,
  surveyId: 'test-survey',
  revision: 1,
  title: '테스트 설문',
  course: { id: 'test', name: '테스트', cohort: '1기' },
  status: 'published',
  createdAt: '2026-10-23T00:00:00.000Z',
  questions: [
    { id: 'major', type: 'single', title: '전공', required: true, options: [{ value: 'yes', label: '전공' }, { value: 'no', label: '비전공' }] },
    { id: 'reason', type: 'longText', title: '이유', showIf: { questionId: 'major', equals: 'no' } },
    { id: 'quiz', type: 'codeQuiz', title: '결과', language: 'text', code: '1 + 1', options: [{ value: '1', label: '1' }, { value: '2', label: '2' }] },
  ],
}

const response = (id: string, answers: SurveyResponse['answers']): SurveyResponse => ({
  schemaVersion: 1,
  surveyId: 'test-survey',
  revision: 1,
  responseId: id,
  submittedAt: '2026-10-23T01:00:00.000Z',
  answers,
})

describe('survey schema', () => {
  it('accepts a valid survey', () => expect(parseSurvey(baseSurvey).surveyId).toBe('test-survey'))
  it('rejects duplicate question ids', () => expect(() => parseSurvey({ ...baseSurvey, questions: [...baseSurvey.questions, baseSurvey.questions[0]] })).toThrow(/중복 문항 ID/))
  it('rejects path-like survey ids', () => expect(() => parseSurvey({ ...baseSurvey, surveyId: '../escape' })).toThrow())
  it('validates response UUID and timestamp', () => expect(parseSurveyResponse(response('10000000-0000-4000-8000-000000000001', { major: 'yes' })).surveyId).toBe('test-survey'))
})

describe('stack question generation', () => {
  const manual: Question = { id: 'manual', type: 'shortText', title: '직접 문항' }
  const definitions: StackDefinition[] = [{ id: 'python', label: 'Python', group: '언어', description: '', questions: [{ id: 'pythonCode', type: 'shortText', title: 'Python' }] }]
  it('adds selected stack questions with provenance', () => {
    const result = syncStackQuestions([manual], ['python'], definitions)
    expect(result).toHaveLength(2)
    expect(result[1]).toMatchObject({ id: 'pythonCode', sourceStack: 'python', autoGenerated: true })
  })
  it('removes only unselected auto-generated questions', () => {
    const withStack = syncStackQuestions([manual], ['python'], definitions)
    expect(syncStackQuestions(withStack, [], definitions)).toEqual([manual])
  })
  it('does not duplicate stack questions', () => expect(syncStackQuestions(syncStackQuestions([manual], ['python'], definitions), ['python'], definitions)).toHaveLength(2))
})

describe('visibility and answer validation', () => {
  it('applies equality conditions', () => expect(isQuestionVisible(baseSurvey.questions[1]!, { major: 'no' })).toBe(true))
  it('hides a conditional question when condition does not match', () => expect(isQuestionVisible(baseSurvey.questions[1]!, { major: 'yes' })).toBe(false))
  it('supports negative equality conditions', () => expect(isQuestionVisible({ ...baseSurvey.questions[1]!, showIf: { questionId: 'major', notEquals: 'yes' } }, { major: 'no' })).toBe(true))
  it('reports missing required answers', () => expect(validateQuestionAnswer(baseSurvey.questions[0]!, undefined)).toBe('필수 문항입니다.'))
})

describe('analytics', () => {
  const responses = [
    response('10000000-0000-4000-8000-000000000001', { major: 'yes', quiz: '2' }),
    response('10000000-0000-4000-8000-000000000002', { major: 'no', reason: '새로운 분야', quiz: '1' }),
  ]
  it('keeps demographic distribution separate and calculates quiz accuracy', () => {
    const result = calculateAnalytics(baseSurvey, responses, { quiz: '2' })
    expect(result.totalResponses).toBe(2)
    expect(result.questions.find((item) => item.questionId === 'major')?.distribution).toHaveLength(2)
    expect(result.questions.find((item) => item.questionId === 'quiz')?.correctRate).toBe(50)
    expect(result.questions.find((item) => item.questionId === 'reason')?.missing).toBe(0)
  })
  it('exports stable CSV columns', () => {
    const csv = responsesToCsv(baseSurvey, responses)
    expect(csv).toContain('"responseId"')
    expect(csv).toContain('"major"')
    expect(csv).toContain('"새로운 분야"')
  })
})
